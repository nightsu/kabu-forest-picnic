import { copyFile, mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import sharp from 'sharp';
import { alphaBounds, packSprites } from './atlas.mjs';

/** Build just the sprites named by the recipe, retaining each original logical frame. */
export async function buildArtwork({ recipe, sourceDir, outputDir }) {
  await mkdir(outputDir, { recursive: true });
  const sprites = {};
  const imports = [];
  for (const [group, definitions] of Object.entries(recipe.groups)) {
    const entries = [];
    for (const [name, definition] of Object.entries(definitions)) {
      const [left, top, width, height] = definition.crop;
      const raw = await sharp(join(sourceDir, definition.source))
        .extract({ left, top, width, height })
        .ensureAlpha()
        .raw()
        .toBuffer();
      const bounds = alphaBounds(raw, width, height);
      const input = await sharp(raw, { raw: { width, height, channels: 4 } })
        .extract(bounds)
        .png()
        .toBuffer();
      entries.push({ name, width: bounds.width, height: bounds.height, input });
      sprites[name] = {
        group,
        size: [width, height],
        offset: [bounds.left, bounds.top],
        anchor: definition.anchor ?? width / 2,
      };
    }
    const sheet = packSprites(entries);
    await sharp({
      create: { width: sheet.width, height: sheet.height, channels: 4, background: '#00000000' },
    })
      .composite(sheet.sprites.map(({ input, left, top }) => ({ input, left, top })))
      .webp({ quality: 88, alphaQuality: 100, effort: 6, smartSubsample: true })
      .toFile(join(outputDir, `${group}.webp`));
    for (const sprite of sheet.sprites) {
      Object.assign(sprites[sprite.name], {
        sheet: [sheet.width, sheet.height],
        region: [sprite.left, sprite.top, sprite.width, sprite.height],
      });
    }
    imports.push(`import ${group}Url from './${group}.webp';`);
  }
  if (recipe.forest) {
    await copyFile(join(sourceDir, recipe.forest), join(outputDir, 'landscape.webp'));
    imports.push("export { default as forestUrl } from './landscape.webp';");
  }
  const records = Object.entries(sprites).map(
    ([name, { group, ...sprite }]) =>
      `${JSON.stringify(name)}: { src: ${group}Url, ${JSON.stringify(sprite).slice(1, -1)} }`,
  );
  await writeFile(
    join(outputDir, 'artwork.ts'),
    `// Generated by npm run art:build from art/recipe.json. Do not edit.\n${imports.join('\n')}\nexport const sprites = {\n${records.join(',\n')}\n} as const;\nexport type SpriteName = keyof typeof sprites;\n`,
  );
  return { sprites };
}
